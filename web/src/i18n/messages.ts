export type Messages = typeof en;

/** Locales that exist. Adding one is a catalogue + this list. */
export type Locale = 'en';

export const catalogues: Record<Locale, Messages> = { en };

/** The active locale. (A user preference lands here later;
 * today the app ships English only.) */
export const activeLocale: Locale = 'en';

/** The active catalogue. Components read strings from `m`. */
export const m: Messages = catalogues[activeLocale];

/**
 * Fill `{placeholder}` slots in a catalogue string. Unknown
 * placeholders are left as-is, which the catalogue test
 * treats as a bug (it compares placeholder sets per key
 * across locales).
 */
export function fmt(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in vars ? String(vars[key]) : whole,
  );
}
