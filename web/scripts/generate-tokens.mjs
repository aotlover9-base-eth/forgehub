#!/usr/bin/env node
/**
 * Generate the ForgeHub design tokens from the single Material
 * You seed colour (#36618E) using
 * @material/material-color-utilities (SchemeTonalSpot, the
 * Material 3 default scheme).
 *
 * Outputs (committed; regenerate with `npm run tokens`):
 *   src/design/tokens.css — --md-sys-color-* + --fh-* tokens
 *   src/design/tokens.ts  — the same values for tests/tooling
 *
 * No colour is chosen by hand anywhere else in the web app;
 * check-tokens.mjs enforces that.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  argbFromHex,
  hexFromArgb,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
} from '@material/material-color-utilities';

const SEED = '#36618E';
const here = dirname(fileURLToPath(import.meta.url));
const designDir = join(here, '..', 'src', 'design');

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'outline', 'outlineVariant', 'scrim', 'shadow',
];

function kebab(camel) {
  return camel.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

function schemeColors(isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
  const out = {};
  for (const role of ROLES) {
    const dynamic = MaterialDynamicColors[role];
    if (!dynamic) throw new Error(`unknown Material role: ${role}`);
    out[kebab(role)] = hexFromArgb(dynamic.getArgb(scheme)).toLowerCase();
  }
  return out;
}

const light = schemeColors(false);
const dark = schemeColors(true);

function colorBlock(colors, indent) {
  return Object.entries(colors)
    .map(([k, v]) => `${indent}--md-sys-color-${k}: ${v};`)
    .join('\n');
}

